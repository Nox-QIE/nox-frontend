// Copies NoxGame + NoxCredits ABIs from a local nox-contracts build into lib/abi.ts.
//   (cd ../nox-contracts && forge build) && npm run sync-abi
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const root = process.argv[2] ?? "../nox-contracts";
const commit = execSync("git rev-parse --short HEAD", { cwd: root }).toString().trim();
let out = `// Generated by scripts/sync-abi.mjs from Nox-QIE/nox-contracts@${commit}. Do not edit.\n\n`;
for (const n of ["NoxGame", "NoxCredits"]) {
  const { abi } = JSON.parse(readFileSync(`${root}/out/${n}.sol/${n}.json`, "utf8"));
  out += `export const ${n}Abi = ${JSON.stringify(abi)} as const;\n\n`;
}
writeFileSync("lib/abi.ts", out);
console.log(`synced ABIs from nox-contracts@${commit}`);
